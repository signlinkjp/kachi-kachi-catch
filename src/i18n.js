/** 端末の言語から対応言語を選ぶ（未対応は英語） */
export function resolveLang(tag) {
  if (!tag) return FALLBACK_LANG;
  const raw = String(tag).toLowerCase().replace("_", "-");
  if (ALIASES[raw]) return ALIASES[raw];
  const base = raw.split("-")[0];
  return ALIASES[base] || FALLBACK_LANG;
}

export function stringsOf(code) {
  return STRINGS[code] || STRINGS[FALLBACK_LANG];
}

/** {name} などを差し込む */
export function format(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}

export function makeT(code) {
  const table = stringsOf(code);
  const fallback = STRINGS[FALLBACK_LANG];
  return function t(key, vars) {
    const raw = table[key] ?? fallback[key] ?? key;
    return vars ? format(raw, vars) : raw;
  };
}

